<?php
require_once __DIR__ . '/../../config/i18n.php';
// ! ADMIN USER DELETE ENDPOINT
// * Deletes one user after confirming authentication, request method, CSRF token, and ID validity.
// ? This endpoint has no HTML because deletion must happen through a POST form from users.php.
if (session_status() !== PHP_SESSION_ACTIVE) {
    session_start();
}

require_once "../../config/database.php";
require_once "../../config/audit.php";

if (!isset($_SESSION["user_id"])) {
	header("Location: ../../auth/login.php");
	exit;
}

if (!isset($_SESSION["user_role"]) || $_SESSION["user_role"] !== "admin") {
	header("Location: ../../index.php");
	exit;
}

// ! Deletion is deliberately POST-only; a link or browser prefetch must never delete an account.
if ($_SERVER["REQUEST_METHOD"] !== "POST") {
	header("Location: users.php");
	exit;
}

$csrfToken = $_POST["csrf_token"] ?? "";
$userId = filter_input(INPUT_POST, "user_id", FILTER_VALIDATE_INT);

// ? Reject requests that do not carry the session token generated by the users page.
if (empty($_SESSION["csrf_token"]) || !hash_equals($_SESSION["csrf_token"], $csrfToken)) {
	header("Location: users.php?error=csrf");
	exit;
}

// ! Never allow the logged-in administrator to remove their own access.
if (!$userId || $userId < 1 || $userId === (int) $_SESSION["user_id"]) {
	header("Location: users.php?error=delete");
	exit;
}

// * The prepared DELETE protects the endpoint from SQL injection.
$deleteStatement = $pdo->prepare("DELETE FROM users WHERE id = ?");
$deleteStatement->execute([$userId]);
auditLog($pdo, (int) $_SESSION["user_id"], "user_deleted", "user", $userId);

header("Location: users.php?success=deleted");
exit;

